#!/usr/bin/env python3
"""Provision ONLY the generated .invalid local identity, without logging factors.

Never use this test shortcut for real invitations or MFA enrollment. It bypasses
the normal enrollment UI so the foundation's password+TOTP/OIDC boundary can be
tested independently. Existing factors are never overwritten.
"""
import json
import os
from pathlib import Path
import re
import subprocess
import sys
from uuid import uuid4

ROOT = Path(__file__).resolve().parents[2]
LOCAL = ROOT / "infra" / "local"


def compose(*args: str) -> str:
    result = subprocess.run(["bash", str(ROOT / "infra/scripts/compose.sh"), *args],
                            capture_output=True, text=True)
    if result.returncode:
        raise RuntimeError("Local test provisioning failed; no secret output emitted.")
    return result.stdout


def main() -> None:
    if os.geteuid() != 0 or not (LOCAL / "READY").exists():
        raise RuntimeError("Requires initialized local test material and root.")
    # Accept only the exact single-user shape generated by bootstrap-local.
    # A substring elsewhere in YAML cannot establish the target user's email.
    test_user = re.fullmatch(
        r"users:\n  pilot:\n    disabled: false\n"
        r"    displayname: 'Lokaler Testnutzer'\n"
        r'    password: ("[^"\r\n]+")\n'
        r"    email: 'pilot@example.invalid'\n"
        r"    groups: \['invited'\]\n",
        (LOCAL / "users.yml").read_text(),
    )
    if not test_user or not json.loads(test_user.group(1)).startswith("$argon2id$"):
        raise RuntimeError("Refusing modified or non-test identity data.")
    manifest = LOCAL / "test-identity.json"
    if manifest.exists():
        print("Local test identity already provisioned; factors kept unchanged.")
        return
    if (LOCAL / "pilot-totp.txt").exists():
        raise RuntimeError("Partial test provisioning exists; inspect before retrying.")
    subject = str(uuid4())
    compose("exec", "-T", "authelia", "authelia", "storage", "user",
            "identifiers", "add", "pilot", "--identifier", subject,
            "--config", "/config/configuration.yml")
    output = compose("exec", "-T", "authelia", "authelia", "storage", "user",
                     "totp", "generate", "pilot",
                     "--issuer", "Investalo Local Test",
                     "--config", "/config/configuration.yml")
    fd = os.open(LOCAL / "pilot-totp.txt", os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w") as stream:
        stream.write(output)
    compose("--profile", "tools", "run", "--rm", "migrate", "python", "-m",
            "investalo_api.provision",
            "--issuer", "https://auth.cockpit.local.test:8443",
            "--subject", subject, "--tenant-name", "Lokale Entwicklung",
            "--role", "owner")
    fd = os.open(manifest, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w") as stream:
        json.dump({"username": "pilot", "subject": subject,
                   "issuer": "https://auth.cockpit.local.test:8443",
                   "tenant_name": "Lokale Entwicklung"}, stream)
        stream.write("\n")
    print("Local .invalid test identity bound to one tenant; MFA factor generated.")
    print("Protected development factor: infra/local/pilot-totp.txt (never logged).")


if __name__ == "__main__":
    try:
        main()
    except (RuntimeError, OSError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
