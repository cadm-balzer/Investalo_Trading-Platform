def actor(db, f, user="a", tenant=None, overrides=None):
    tenant = tenant or user
    settings = {
        "app.user_id": str(f["user_" + user]), "app.tenant_id": str(f["tenant_" + tenant]),
        "app.oidc_issuer": f["runtime"].oidc_issuer, "app.oidc_subject": f["subject_" + user],
    }
    settings.update(overrides or {})
    for key, value in settings.items():
        db.execute("SELECT set_config(%s,%s,true)", (key, value))


def now(db):
    # ceil permits an assertion after subsecond reauth_after. Five-second
    # future tolerance is checked by SQL and timestamps are generated by PG.
    return db.execute(
        "SELECT ceil(extract(epoch FROM clock_timestamp()))::bigint AS value"
    ).fetchone()["value"]


def issue(f, *, user="a", rp=RP, ttl=300, epoch=0, token_hash=None, handle=None):
    token_hash = token_hash or sha256(secrets.token_bytes(32)).digest()
    handle = handle or secrets.token_bytes(32)
    with connect(f["admin"]) as db:
        deadline = db.execute("SELECT clock_timestamp() AS value").fetchone()["value"] + timedelta(seconds=ttl)
        ticket = db.execute(
            ISSUE, (f["tenant_" + user], f["user_" + user], rp, token_hash, handle,
                    epoch, deadline, uuid4()),
        ).fetchone()["ticket_id"]
    return {"ticket_id": ticket, "token_hash": token_hash, "user_handle": handle, "rp": rp}


def claim(f, ticket, *, user="a", binding=None, epoch=0):
    binding = binding or secrets.token_bytes(32)
    with connect(f["runtime"]) as db:
        actor(db, f, user)
        result = db.execute(CLAIM, (ticket["token_hash"], ticket["rp"], binding, epoch, now(db))).fetchone()
    # Exiting the connection commits the one-use claim before any verifier.
    return {**ticket, **result, "binding": binding}


def finish(f, ticket, *, user="a", counter=0, be=True, bs=False, epoch=0, credential=None, key=None):
    credential = credential or secrets.token_bytes(32)
    key = key or b"synthetic-public-key-not-a-WebAuthn-proof"
    with connect(f["runtime"]) as db:
        actor(db, f, user)
        return db.execute(
            FINISH, (ticket["claim_id"], ticket["binding"], credential, key, counter, be, bs, epoch, now(db)),
        ).fetchone()


def read(f, *, user="a", rp=RP, epoch=0):
    with connect(f["runtime"]) as db:
        actor(db, f, user)
        return db.execute(READ, (rp, epoch, now(db))).fetchone()


def update_counter(f, row, *, counter=0, bs=False, version=None, epoch=0, user="a"):
    with connect(f["runtime"]) as db:
        actor(db, f, user)
        return db.execute(
            CAS, (row["passkey_id"], row["storage_version"] if version is None else version,
                  counter, bs, epoch, now(db)),
        ).fetchone()


def denied(operation, code="42501"):
    with pytest.raises(psycopg.Error) as failure:
        operation()
    assert failure.value.sqlstate == code
    assert failure.value.diag.message_primary in ("access_denied", "invalid_record", "concurrent_change")


