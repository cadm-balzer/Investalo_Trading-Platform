@pytest.mark.parametrize("operation", ["claim", "finish"])
def test_expiry_while_waiting_for_actor_rp_slot_never_publishes_a_result(passkey_database, operation):
    f = passkey_database
    ticket = issue(f, ttl=2)
    if operation == "finish":
        ticket = claim(f, ticket)
    pids = Queue()
    with ThreadPoolExecutor(max_workers=1) as pool:
        with connect(f["admin"]) as blocking:
            blocking.execute("SELECT platform.passkey_slot(%s,%s,%s)", (f["tenant_a"], f["user_a"], RP))
            def run():
                with connect(f["runtime"]) as db:
                    actor(db, f)
                    auth_time = now(db)
                    pids.put(db.info.backend_pid)
                    try:
                        if operation == "claim":
                            db.execute(CLAIM, (ticket["token_hash"], RP, secrets.token_bytes(32), 0, auth_time))
                        else:
                            db.execute(FINISH, (ticket["claim_id"], ticket["binding"], b"id", b"key",
                                                0, True, False, 0, auth_time))
                    except psycopg.Error as error:
                        return error.sqlstate
                    return "unexpected_success"
            future = pool.submit(run)
            pid = pids.get(timeout=5)
            stop = monotonic() + 1
            while True:
                waiting = blocking.execute(
                    "SELECT 1 FROM pg_catalog.pg_locks WHERE pid=%s AND locktype='advisory' AND NOT granted",
                    (pid,),
                ).fetchone()
                if waiting:
                    break
                assert monotonic() < stop, "Runtime did not reach the deliberately blocked slot"
                sleep(0.02)
            remaining = blocking.execute(
                "SELECT extract(epoch FROM (expires_at-clock_timestamp())) AS remaining "
                "FROM platform.passkey_enrollment_tickets WHERE ticket_id=%s",
                (ticket["ticket_id"],),
            ).fetchone()["remaining"]
            sleep(max(0.0, float(remaining)) + 0.05)
            # Commit releases the slot only after the ticket has really expired.
        assert future.result(timeout=5) == "42501"
    assert read(f) is None
    with connect(f["admin"]) as db:
        events = db.execute(
            "SELECT event FROM platform.passkey_audit WHERE ticket_id=%s ORDER BY occurred_at",
            (ticket["ticket_id"],),
        ).fetchall()
        assert events == ([{"event": "issued"}] if operation == "claim" else
                          [{"event": "issued"}, {"event": "claimed"}])


