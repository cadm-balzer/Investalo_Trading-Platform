"""Conservative OHLC paper reference. No discretionary sixth-stage fabrication."""

from __future__ import annotations

from dataclasses import dataclass, replace
from datetime import datetime, timedelta
from decimal import Decimal, localcontext
from itertools import groupby
from typing import Iterable

from .engine import CryptoEngine
from .models import (
    Candle, DomainEvent, EngineState, Fill, OrderRecord, OrderStatus, Quote,
    Side, TradingRejected, Transition, floor_step, positive, precise,
)
from .snapshot import digest

D = Decimal


@dataclass(frozen=True)
class SimulationCosts:
    """Explicit research assumptions; not live Bitget fee or liquidity metadata."""

    fee_rate: Decimal = D("0.001")
    spread_fraction: Decimal = D("0.001")
    slippage_fraction: Decimal = D("0.001")

    def __post_init__(self) -> None:
        for field in ("fee_rate", "spread_fraction", "slippage_fraction"):
            value = getattr(self, field)
            positive(value, field, zero=True)
            if value >= 1:
                raise ValueError("cost fractions must be below one")


@dataclass(frozen=True)
class EquityPoint:
    at: datetime
    equity: Decimal


@dataclass(frozen=True)
class BacktestResult:
    strategy_version: str
    configuration_digest: str
    data_digest: str
    cost_digest: str
    state: EngineState
    equity_curve: tuple[EquityPoint, ...]
    events: tuple[DomainEvent, ...]
    fills: tuple[Fill, ...]
    net_pnl: Decimal
    maximum_drawdown_fraction: Decimal
    profit_factor: Decimal | None
    closed_basket_count: int
    manual_fills_fabricated: bool = False
    execution_assumption: str = "next_open_buy; adverse_low_then_high_then_close; no_terminal_flatten"


@dataclass(frozen=True)
class PaperSimulator:
    engine: CryptoEngine = CryptoEngine()
    costs: SimulationCosts = SimulationCosts()

    def __post_init__(self) -> None:
        if (self.engine.config.estimated_exit_fee_rate != self.costs.fee_rate
                or self.engine.config.estimated_exit_slippage_fraction != self.costs.slippage_fraction):
            raise ValueError("engine exit cost assumptions must match simulation costs")

    def settle(self, state: EngineState, at: datetime, *, buys: bool = True,
               symbols: tuple[str, ...] | None = None,
               require_later_buy_quote: bool = False) -> tuple[
            EngineState, tuple[Fill, ...], tuple[DomainEvent, ...]]:
        """Execute existing PAPER intents; never create a discretionary intent.

        Caller first applies current quotes, and authenticates manual approvals
        in the application layer. Unknown orders require explicit reconciliation.
        """
        self.engine._validate(state)
        return self._settle(state, at, buys=buys, symbols=symbols,
                            require_later_buy_quote=require_later_buy_quote)

    @precise
    def quote(self, symbol: str, at: datetime, midpoint: Decimal) -> Quote:
        return Quote(symbol, at, midpoint * (1 - self.costs.spread_fraction / 2),
                     midpoint * (1 + self.costs.spread_fraction / 2))

    @precise
    def _settle(self, state: EngineState, at: datetime, *, buys: bool,
                symbols: tuple[str, ...] | None = None,
                require_later_buy_quote: bool = False) -> tuple[EngineState, tuple[Fill, ...], tuple[DomainEvent, ...]]:
        """Simulator's authoritative execution/cancellation, never a broker retry."""
        fills: list[Fill] = []
        events: list[DomainEvent] = []
        # New safety exits generated by a fill are handled in subsequent iterations.
        for _ in range(20):
            changed = False
            for old in state.orders:
                record = next(o for o in state.orders if o.intent.intent_id == old.intent.intent_id)
                if not record.unresolved:
                    continue
                if record.status == OrderStatus.UNKNOWN:
                    raise TradingRejected("simulator_cannot_resolve_unknown_broker_order")
                if symbols is not None and record.intent.symbol not in symbols:
                    continue
                if record.status == OrderStatus.CANCEL_REQUESTED:
                    result = self.engine.reconcile_cancelled(state, record.intent.intent_id)
                    state = result.state
                    events.extend(result.events)
                    changed = True
                    continue
                intent = record.intent
                quote = state.quote(intent.symbol)
                if quote is None:
                    continue
                if intent.side == Side.BUY:
                    if not buys:
                        continue
                    if intent.created_at > at:
                        continue
                    if require_later_buy_quote and quote.observed_at <= intent.created_at:
                        continue
                    reject = self.engine._buy_rejection_for_dispatch(state, record, at)
                    with localcontext() as ctx:
                        ctx.prec = 36
                        price = quote.ask * (1 + self.costs.slippage_fraction)
                        remaining = intent.maximum_quote - record.filled_principal
                        quantity = floor_step(remaining / price, self.engine.rules(intent.symbol).quantity_step)
                    if reject or quantity <= 0 or (intent.maximum_price is not None and price > intent.maximum_price):
                        result = self.engine.reconcile_cancelled(state, intent.intent_id)
                        state = result.state
                        events.extend(result.events)
                        events.append(DomainEvent("simulated_order_cancelled", intent.symbol, intent.intent_id,
                                                  reject or "price_or_quantity_limit"))
                        changed = True
                        continue
                else:
                    basket = state.basket(intent.symbol)
                    quantity = min(basket.quantity, intent.quantity - record.filled_quantity)
                    if quantity <= 0:
                        result = self.engine.reconcile_cancelled(state, intent.intent_id)
                        state = result.state
                        changed = True
                        continue
                    price = quote.bid * (1 - self.costs.slippage_fraction)
                principal = quantity * price
                fill = Fill(
                    "paper-" + digest((intent.intent_id, at.isoformat(), str(record.filled_quantity)))[:32],
                    intent.intent_id, at + timedelta(microseconds=1), quantity, price,
                    principal * self.costs.fee_rate, final=True,
                )
                result = self.engine.apply_fill(state, fill)
                state = result.state
                fills.append(fill)
                events.extend(result.events)
                changed = True
            if not changed:
                return state, tuple(fills), tuple(events)
        raise RuntimeError("paper execution failed to converge")

    @precise
    def run(self, candles: Iterable[Candle], *, tenant_id: str = "research",
            account_id: str = "paper-reference") -> BacktestResult:
        bars = tuple(sorted(candles, key=lambda b: (b.open_time, b.symbol)))
        if not bars:
            raise ValueError("at least one H4 candle is required")
        if len({(b.symbol, b.open_time) for b in bars}) != len(bars):
            raise ValueError("duplicate input candle")
        for symbol in {b.symbol for b in bars}:
            sequence = tuple(b for b in bars if b.symbol == symbol)
            if any(b.open_time != a.close_time for a, b in zip(sequence, sequence[1:])):
                raise ValueError("history contains a gap; do not silently interpolate")
        state = self.engine.start(tenant_id, account_id, bars[0].open_time)
        curve: list[EquityPoint] = [EquityPoint(bars[0].open_time, state.equity)]
        fills: list[Fill] = []
        events: list[DomainEvent] = []
        for opened, grouping in groupby(bars, lambda b: b.open_time):
            group = tuple(grouping)
            phases = (
                (opened, "open", True),
                (opened + timedelta(hours=1), "low", False),
                (opened + timedelta(hours=2), "high", False),
                (opened + timedelta(hours=4), "close", False),
            )
            for at, price_field, buys in phases:
                for bar in group:
                    result = self.engine.on_quote(state, self.quote(bar.symbol, at, getattr(bar, price_field)))
                    state = result.state
                    events.extend(result.events)
                if at.hour == 0 and not at.minute and not at.second:
                    state = self.engine.reset_day(state, at)
                state, new_fills, new_events = self._settle(state, at, buys=buys)
                fills.extend(new_fills)
                events.extend(new_events)
                if price_field == "close":
                    for bar in group:
                        result = self.engine.on_bar(state, bar, observed_at=at)
                        state = result.state
                        events.extend(result.events)
                    state, new_fills, new_events = self._settle(state, at, buys=False)
                    fills.extend(new_fills)
                    events.extend(new_events)
                curve.append(EquityPoint(at, state.equity))
        # An unexecuted final signal is not a fill at the final known close.
        for order in state.orders:
            if order.unresolved and order.intent.side == Side.BUY:
                state = self.engine.reconcile_cancelled(state, order.intent.intent_id).state
        with localcontext() as ctx:
            ctx.prec = 36
            high_water = curve[0].equity
            drawdown = D("0")
            for point in curve:
                high_water = max(high_water, point.equity)
                drawdown = max(drawdown, (high_water - point.equity) / high_water)
            gains = sum((c.net_pnl for c in state.closed_baskets if c.net_pnl > 0), D("0"))
            losses = -sum((c.net_pnl for c in state.closed_baskets if c.net_pnl < 0), D("0"))
            factor = gains / losses if losses else None
        return BacktestResult(
            self.engine.config.version, state.configuration_digest, digest(bars), digest(self.costs),
            state, tuple(curve), tuple(events), tuple(fills),
            state.equity - state.account.initial_equity, drawdown, factor, len(state.closed_baskets),
        )
